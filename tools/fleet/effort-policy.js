'use strict';
// effort-policy.js — T004 (004-elt-selfdrive): адаптивный эффорт петли.
//
// Боль (скан 278 сессий: 37× ручной /effort, 7 stuck-loop сессий ≥4 подряд красных):
// модель «не тянет» долгий багфикс и молотит на одном уровне способностей. Политика:
//   impl-фаза  → 'high'  (дефолт — экономим токены на рутине слайса);
//   heal-фаза  → 'max'   (self-heal после красного оракула — дать максимум ТОЛЬКО на починку).
// «Назад на high следующего слайса» — автоматически: петля per-слайс без состояния, каждый
// новый слайс стартует с impl='high'. Единый источник уровней — здесь (драйвер объявляет
// ФАЗУ, не хардкодит уровень), поэтому политику меняем в одном месте и она под тестом.
const IMPL_EFFORT = 'high';
const HEAL_EFFORT = 'max';

// unknown/пустая фаза → 'high' (безопасный дефолт: не эскалируем зря, не тратим токены).
function effortFor(phase) { return phase === 'heal' ? HEAL_EFFORT : IMPL_EFFORT; }

module.exports = { effortFor, IMPL_EFFORT, HEAL_EFFORT };
